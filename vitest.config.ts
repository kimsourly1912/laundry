import { globSync, readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { Plugin } from 'vitest/config'
import { configDefaults, defineConfig } from 'vitest/config'
import { defineVitestProject } from '@nuxt/test-utils/config'

const path = (relative: string) => fileURLToPath(new URL(relative, import.meta.url))
/** The project root with forward slashes, as Vitest matches file globs. */
const root = path('.').replaceAll('\\', '/').replace(/\/$/, '')

const NUXT_TESTS = ['test/nuxt/**/*.test.ts', 'app/features/*/tests/**/*.nuxt.test.ts']

/** Nuxt aliases that plain-Node projects (unit, server) need. */
const alias = {
  '#shared': path('./shared'),
  '#server': path('./server'),
  // The app's own alias, for pure feature code that imports a root util explicitly.
  '~': path('./app'),
  // Generated by `nuxt prepare` (postinstall) from the Better Auth config.
  '#auth/schema': path('./.nuxt/better-auth/schema.mjs'),
  // Every table NuxtHub knows (ours + Better Auth's with plugins), generated by `nuxt prepare`.
  'hub:db:schema': path('./.nuxt/hub/db/schema.mjs'),
}

/**
 * The two build-time imports Nitro resolves for the server (server/assets.d.ts), done the same way
 * for tests: `raw:<path>` is the file's bytes, `<package>.wasm?module` a compiled WebAssembly module.
 */
function serverAssets(): Plugin {
  const RAW = '?laundry-raw'
  // A virtual id (Vite's `\0` prefix), or Vitest would hand the file to Node's own loader, which
  // can't read an encoded Windows path (`C:/…`) as a file URL.
  const WASM = '\0laundry-wasm-module:'
  return {
    name: 'laundry:server-assets',
    enforce: 'pre',
    async resolveId(id, importer) {
      if (id.startsWith('raw:') && importer) return resolve(dirname(importer), id.slice(4)) + RAW
      if (id.endsWith('.wasm?module')) {
        const resolved = await this.resolve(id.slice(0, -'?module'.length), importer, { skipSelf: true })
        return resolved && WASM + encodeURIComponent(resolved.id)
      }
    },
    load(id) {
      if (id.endsWith(RAW)) return `export default new Uint8Array(Buffer.from(${JSON.stringify(readFileSync(id.slice(0, -RAW.length)).toString('base64'))}, 'base64'))`
      if (id.startsWith(WASM)) return `import { readFileSync } from 'node:fs'\nexport default new WebAssembly.Module(readFileSync(${JSON.stringify(decodeURIComponent(id.slice(WASM.length)))}))`
    },
  }
}

// Tests live next to what they test:
// - app feature tests: app/features/<name>/tests/*.test.ts
// - server feature tests: server/features/<name>/tests/*.test.ts
// - shared code tests: test/unit, test/nuxt, test/e2e, server/tests
// `*.nuxt.test.ts` runs in the Nuxt environment (auto-imports, components); everything else in plain Node.
export default defineConfig({
  test: {
    // `--changed` follows imports; server tests will read the migrations from disk (M1.3), so a
    // migration-only change would run nothing. Changing one, package.json or this file reruns everything.
    forceRerunTriggers: [
      ...configDefaults.forceRerunTriggers,
      ...['package.json', 'vitest.config.*', 'server/db/migrations/**'].map(glob => `${root}/${glob}`),
    ],
    projects: [
      {
        resolve: { alias },
        test: {
          name: 'unit',
          include: ['test/unit/**/*.test.ts', 'app/features/*/tests/**/*.test.ts', 'shared/**/*.test.ts'],
          exclude: ['**/*.nuxt.test.ts'],
          environment: 'node',
        },
      },
      {
        // Server services against SQLite built from the real migrations (server/tests/support/db.ts).
        resolve: { alias },
        plugins: [serverAssets()],
        test: {
          name: 'server',
          include: ['server/tests/**/*.test.ts', 'server/features/*/tests/**/*.test.ts'],
          // Runs the migrations once; each test database replays the result.
          globalSetup: ['server/tests/support/global-setup.ts'],
          // Closes every test database: libsql crashes the worker when the GC frees an open one.
          setupFiles: ['server/tests/support/setup.ts'],
          environment: 'node',
        },
      },
      {
        // Builds and serves the app once, on a seeded database, for every e2e file (test/e2e/support).
        resolve: { alias },
        test: {
          name: 'e2e',
          include: ['test/e2e/**/*.test.ts'],
          environment: 'node',
          globalSetup: ['test/e2e/support/global-setup.ts'],
          // A test drives whole flows, sometimes on two devices.
          testTimeout: 60_000,
          hookTimeout: 60_000,
          // A cold page (session check, then redirect) can take more than expect.poll's default 1 s.
          expect: { poll: { timeout: 10_000 } },
        },
      },
      // Loading Nuxt for this project runs NuxtHub's module setup, which rewrites .data and can race
      // with a running dev server. The project exists only once a Nuxt-environment test does.
      ...(globSync(NUXT_TESTS).length
        ? [await defineVitestProject({ test: { name: 'nuxt', include: NUXT_TESTS, environment: 'nuxt' } })]
        : []),
    ],
  },
})
